"""
Copies the game's own words for everything the site names into src/i18n/game-text.ts.

  python scripts/sync-game-text.py "C:/Users/Digikey/Desktop/GlimmerGrove/Assets/StreamingAssets/Content/loc"
  python scripts/sync-game-text.py --check "<same path>"

Turret, kit, chapter, level, boss and companion names, and the in-game button labels the
policies quote, are read from the game's loc tables (`loc/{lang}.json`) rather than
translated a second time here. A player who reads "Ocultarme de la clasificación" on the
deletion page has to find exactly that on the Profile screen; two translations of one
button would drift apart the first time either side was edited.

The generated file is committed. Re-run this whenever the game's loc tables change, and
`--check` fails (exit 1) when the committed file no longer matches them.
"""
import json, os, sys

LOCALES = ["en", "es", "pt", "fr", "de", "it", "tr", "pl"]

CHAPTERS = {
    "thornwatch": ("s01_thornwatch", "mode.siege.boss",
                   ["firstwatch", "ironward", "stonewatch", "thornhollow", "warlordsgate",
                    "bramblerun", "ashenfield", "blackmarch", "thornsiege", "lastlight"]),
    "broodmarch": ("s03_broodmarch", "mode.siege.blightcaller",
                   ["firstbrood", "hollowshell", "mirewalk", "spinecrest", "blightfen",
                    "stillmire", "thornbrood", "gloamfield", "deepmire", "broodheart"]),
    "barrowfell": ("s04_barrowfell", "mode.siege.gravemaw",
                   ["firstbone", "palerow", "shieldwall", "scytheway", "hollowgrave",
                    "boneyard", "deadmarch", "lichgate", "longbarrow", "barrowheart"]),
}

TURRETS = ["bolt", "siphon", "beacon", "ember", "rime", "cleaver", "prism", "lance", "mortar",
           "spark", "leech", "lighthouse", "pyre", "glacier", "breaker", "spectrum", "harpoon",
           "howitzer", "arcstorm", "apex"]

KIT = ["firepot", "mending", "surge", "stormcall"]

# Board charms, named by their tip's title (the game draws these in capitals).
CHARMS = {"prism": "ui.tip.siege_prism.title", "lance": "ui.tip.siege_lance.title",
          "stormglass": "ui.tip.siege_storm.title"}

COMPANIONS = ["monarch", "cinder", "timber", "sorrel", "sprocket", "peep", "thistle", "gourd",
              "puff", "clementine", "plum", "frond", "button", "shell", "dewdrop", "flit",
              "toadstool", "quill", "olive", "indigo", "tadpole", "pebble", "saffron", "coral",
              "rust", "fizz", "marrow", "bramble", "wisp", "boulder", "thorn"]

# Labels the policies and support page quote. Exact case, exactly as the button reads.
LABELS = {
    "deleteAccount": "ui.delete.title",
    "deleteEverything": "ui.delete.confirm",
    "privacyChoices": "ui.settings.privacy",
    "restorePurchases": "ui.shop.restore",
    "hideFromBoards": "ui.board.leave",
    "report": "ui.visit.report",
}

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "src", "i18n", "game-text.ts")


def load(loc_dir):
    tables = {}
    for lang in LOCALES:
        with open(os.path.join(loc_dir, f"{lang}.json"), encoding="utf-8") as f:
            tables[lang] = {e["key"]: e["text"] for e in json.load(f)["entries"]}
    return tables


def build(tables):
    missing = []

    def get(lang, key):
        text = tables[lang].get(key)
        if text is None:
            missing.append(f"{lang}:{key}")
            return ""
        return text

    out = {}
    for lang in LOCALES:
        g = lambda key: get(lang, key)
        out[lang] = {
            "chapters": {
                cid: {
                    "name": g(f"chapter.{chap}.name"),
                    "boss": g(boss),
                    "levels": [g(f"level.{chap.split('_')[0]}_{lvl}.name") for lvl in levels],
                }
                for cid, (chap, boss, levels) in CHAPTERS.items()
            },
            "endless": {
                "name": g("chapter.s02_endlesswatch.name"),
                "tagline": g("level.s02_endless.tagline"),
            },
            "turrets": {t: {"name": g(f"ward.{t}.name"), "note": g(f"ward.{t}.note")} for t in TURRETS},
            "kit": {k: {"name": g(f"utility.{k}.name"), "note": g(f"utility.{k}.note")} for k in KIT},
            "charms": {c: g(key) for c, key in CHARMS.items()},
            "companions": [g(f"ui.avatar.{c}") for c in COMPANIONS],
            "labels": {name: g(key) for name, key in LABELS.items()},
        }

    if missing:
        sys.exit("missing loc keys:\n  " + "\n  ".join(missing))
    return out


def render(data):
    body = json.dumps(data, ensure_ascii=False, indent=2)
    return (
        "/*\n"
        " * GENERATED by scripts/sync-game-text.py from the game's loc tables. Do not edit by hand:\n"
        " * change the game's text and re-run the script, so the site and the game cannot disagree\n"
        " * about what a turret or a button is called.\n"
        " */\n\n"
        "import type { Locale } from \"@/i18n/locales\";\n\n"
        f"const gameText = {body} as const;\n\n"
        "export type GameText = (typeof gameText)[\"en\"];\n\n"
        "/** The game's own words, in the game's own translation. */\n"
        "export function gameTextFor(locale: Locale) {\n"
        "  return gameText[locale] as unknown as GameText;\n"
        "}\n"
    )


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv
    loc_dir = args[0] if args else os.path.join(
        os.path.expanduser("~"), "Desktop", "GlimmerGrove", "Assets", "StreamingAssets", "Content", "loc")
    text = render(build(load(loc_dir)))
    if check:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            sys.exit("src/i18n/game-text.ts is stale: re-run scripts/sync-game-text.py")
        print("game-text.ts matches the game's loc tables")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
